// RenderConfig returns headscale's config.yaml.
func RenderConfig(c Config) (string, error) {
	c.defaults()
	if c.ServerURL == "" {
		return "", fmt.Errorf("server_url is required")
	}
	var b bytes.Buffer
	err := configTmpl.Execute(&b, c)
	return b.String(), err
}

// RenderDERP returns /etc/headscale/derp.yaml (an extra self-hosted DERP
// region when DERPHost is set, else an empty region list).
func RenderDERP(c Config) string {
	c.defaults()
	if c.DERPHost == "" {
		return "# Generated by Boxaz core: no extra DERP region (embedded DERP + Tailscale public map are used).\nregions: {}\n"
	}
	return fmt.Sprintf(`# Generated by Boxaz core: self-hosted DERP relay.
regions:
  %d:
    regionid: %d
    regioncode: boxaz-relay
    regionname: Boxaz relay
    nodes:
      - name: %da
        regionid: %d
        hostname: %s
        derpport: %d
        stunport: 3478
`, c.DERPRegionID+1, c.DERPRegionID+1, c.DERPRegionID+1, c.DERPRegionID+1, c.DERPHost, c.DERPPort)
}

// ---- ACL policy ----

// Box is the input the ACL generator needs about one box.
type Box struct {
	ID            string
	AgentID       string
	Ports         []int
	EgressAllow   []string // domains, *.domains, IPs, CIDRs with optional :port
	DenyByDefault bool
}

// Policy is a headscale/Tailscale policy file (JSON form).
type Policy struct {
	Groups    map[string][]string `json:"groups"`
	TagOwners map[string][]string `json:"tagOwners"`
	Hosts     map[string]string   `json:"hosts,omitempty"`
	ACLs      []ACL               `json:"acls"`
	Notes     []string            `json:"-"`
}

// ACL is one accept rule.
type ACL struct {
	Action string   `json:"action"`
	Src    []string `json:"src"`
	Dst    []string `json:"dst"`
}

// TagHost / TagCore / AgentTag / BoxTag name the tags Boxaz uses.
const (
	TagHost = "tag:boxaz-host"
	TagCore = "tag:boxaz-core"
)

func AgentTag(agentID string) string { return "tag:agent-" + sanitize(agentID) }
func BoxTag(boxID string) string     { return "tag:box-" + sanitize(boxID) }

func sanitize(s string) string {
	s = strings.ToLower(s)
	var b strings.Builder
	for _, r := range s {
		if r >= 'a' && r <= 'z' || r >= '0' && r <= '9' || r == '-' {
			b.WriteRune(r)
		} else {
			b.WriteRune('-')
		}
	}
	return b.String()
}

// GeneratePolicy builds the policy: core ⇄ hosts, boxes of the same agent
// can reach each other's exposed ports, and each box may reach the IP/CIDR
// entries of its egress allowlist (domains cannot be expressed in a tailnet
// ACL and stay enforced by the host firewall). Everything else is denied
// (tailnet default deny).
func GeneratePolicy(c Config, boxes []Box) Policy {
	c.defaults()
	owner := c.User + "@"
	p := Policy{Groups: map[string][]string{"group:boxaz-admin": {owner}}, TagOwners: map[string][]string{TagHost: {owner}, TagCore: {owner}}, Hosts: map[string]string{}}
	p.ACLs = append(p.ACLs,
		ACL{"accept", []string{TagCore, "group:boxaz-admin"}, []string{TagHost + ":*"}},
		ACL{"accept", []string{TagHost}, []string{fmt.Sprintf("%s:443,%d", TagCore, c.CorePort)}},
	)
	byAgent := map[string][]Box{}
	for _, b := range boxes {
		byAgent[b.AgentID] = append(byAgent[b.AgentID], b)
	}
	agents := make([]string, 0, len(byAgent))
	for a := range byAgent {
		agents = append(agents, a)
	}
	sort.Strings(agents)
	for _, a := range agents {
		at := AgentTag(a)
		p.TagOwners[at] = []string{owner}
		list := byAgent[a]
		sort.Slice(list, func(i, j int) bool { return list[i].ID < list[j].ID })
		var dst []string
		for _, b := range list {
			bt := BoxTag(b.ID)
			p.TagOwners[bt] = []string{owner}
			if len(b.Ports) == 0 {
				continue
			}
			ports := make([]string, len(b.Ports))
			for i, x := range b.Ports {
				ports[i] = fmt.Sprint(x)
			}
			dst = append(dst, bt+":"+strings.Join(ports, ","))
		}
		if len(dst) > 0 {
			p.ACLs = append(p.ACLs, ACL{"accept", []string{at}, dst})
		}
		p.ACLs = append(p.ACLs, ACL{"accept", []string{TagCore}, []string{at + ":*"}})
		for _, b := range list {
			var eg []string
			for _, e := range b.EgressAllow {
				if d, ok := aclDest(e); ok {
					eg = append(eg, d)
				} else {
					p.Notes = append(p.Notes, fmt.Sprintf("%s: %q is a domain; enforced by the host firewall, not the tailnet ACL", b.ID, e))
				}
			}
			if len(eg) > 0 {
				p.ACLs = append(p.ACLs, ACL{"accept", []string{BoxTag(b.ID)}, eg})
			}
		}
	}
	return p
}

// aclDest converts an IP / CIDR [:port] egress entry to an ACL destination.
func aclDest(e string) (string, bool) {
	e = strings.TrimSpace(e)
	host, port := e, "*"
	if i := strings.LastIndex(e, ":"); i > 0 && !strings.Contains(e[:i], ":") {
		host, port = e[:i], e[i+1:]
	}
	if ip := net.ParseIP(host); ip != nil {
		return host + ":" + port, true
	}
	if _, n, err := net.ParseCIDR(host); err == nil {
		return n.String() + ":" + port, true
	}
	return "", false
}

// JSON renders the policy as indented JSON.
func (p Policy) JSON() string {
	b, _ := json.MarshalIndent(p, "", "  ")
	return string(b)
}

// ---- headscale REST client ----

// Client talks to the headscale REST API (/api/v1, Bearer API key).
type Client struct {
	BaseURL string
	APIKey  string
	HTTP    *http.Client
}

// Node is a headscale node.
type Node struct {
	ID          string    `json:"id"`
	Name        string    `json:"name"`
	GivenName   string    `json:"givenName"`
	IPAddresses []string  `json:"ipAddresses"`
	Online      bool      `json:"online"`
	LastSeen    time.Time `json:"lastSeen"`
	ForcedTags  []string  `json:"forcedTags"`
	ValidTags   []string  `json:"validTags"`
	User        struct {
		Name string `json:"name"`
	} `json:"user"`
}

// PreAuthKey is a created key.
type PreAuthKey struct {
	ID         string    `json:"id"`
	Key        string    `json:"key"`
	Reusable   bool      `json:"reusable"`
	Ephemeral  bool      `json:"ephemeral"`
	Expiration time.Time `json:"expiration"`
	ACLTags    []string  `json:"aclTags"`
}

func (c *Client) do(ctx context.Context, method, path string, body, out any) error {
	var rd io.Reader
	if body != nil {
		b, _ := json.Marshal(body)
		rd = bytes.NewReader(b)
	}
	req, err := http.NewRequestWithContext(ctx, method, strings.TrimRight(c.BaseURL, "/")+path, rd)
	if err != nil {
		return err
	}
	req.Header.Set("Authorization", "Bearer "+c.APIKey)
	req.Header.Set("Content-Type", "application/json")
	hc := c.HTTP
	if hc == nil {
		hc = &http.Client{Timeout: 15 * time.Second}
	}
	resp, err := hc.Do(req)
	if err != nil {
		return err
	}
	defer resp.Body.Close()
	b, _ := io.ReadAll(io.LimitReader(resp.Body, 4<<20))
	if resp.StatusCode >= 300 {
		return fmt.Errorf("headscale HTTP %d: %s", resp.StatusCode, strings.TrimSpace(string(b)))
	}
	if out != nil && len(b) > 0 {
		return json.Unmarshal(b, out)
	}
	return nil
}

// EnsureUser creates the user when missing.
func (c *Client) EnsureUser(ctx context.Context, name string) error {
	var users struct {
		Users []struct {
			Name string `json:"name"`
		} `json:"users"`
	}
	if err := c.do(ctx, "GET", "/api/v1/user", nil, &users); err != nil {
		return err
	}
	for _, u := range users.Users {
		if u.Name == name {
			return nil
		}
	}
	return c.do(ctx, "POST", "/api/v1/user", map[string]string{"name": name}, nil)
}

// CreatePreAuthKey creates a (single-use by default) key with ACL tags.
func (c *Client) CreatePreAuthKey(ctx context.Context, user string, tags []string, reusable, ephemeral bool, ttl time.Duration) (*PreAuthKey, error) {
	if ttl <= 0 {
		ttl = time.Hour
	}
	body := map[string]any{"user": user, "reusable": reusable, "ephemeral": ephemeral,
		"expiration": time.Now().UTC().Add(ttl).Format(time.RFC3339), "aclTags": tags}
	var out struct {
		PreAuthKey PreAuthKey `json:"preAuthKey"`
	}
	if err := c.do(ctx, "POST", "/api/v1/preauthkey", body, &out); err != nil {
		return nil, err
	}
	if out.PreAuthKey.Key == "" {
		return nil, fmt.Errorf("headscale returned no key")
	}
	return &out.PreAuthKey, nil
}

// Nodes lists nodes (optionally of one user).
func (c *Client) Nodes(ctx context.Context, user string) ([]Node, error) {
	p := "/api/v1/node"
	if user != "" {
		p += "?user=" + url.QueryEscape(user)
	}
	var out struct {
		Nodes []Node `json:"nodes"`
	}
	if err := c.do(ctx, "GET", p, nil, &out); err != nil {
		return nil, err
	}
	if out.Nodes == nil {
		out.Nodes = []Node{}
	}
	return out.Nodes, nil
}

// TailscaleUpArgs is the command boxd runs to join (no shell, explicit args).
func TailscaleUpArgs(loginServer, authKey, hostname string, tags []string) []string {
	args := []string{"up", "--login-server=" + loginServer, "--authkey=" + authKey, "--hostname=" + hostname, "--accept-dns=false", "--reset"}
	if len(tags) > 0 {
		args = append(args, "--advertise-tags="+strings.Join(tags, ","))
	}
	return args
}
