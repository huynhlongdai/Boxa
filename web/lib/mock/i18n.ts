/** Định dạng thông điệp mock: {name} → giá trị (không phải ICU, đủ cho mock). */
export function mt(locale: Locale, key: string, params: Record<string, string | number> = {}): string {
  const tpl = DICTS[locale]?.[key] ?? DICTS.en[key] ?? key;
  return tpl.replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : m));
}

